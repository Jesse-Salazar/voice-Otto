const historyPath = path.join(__dirname, "processed-projects.json");
let activeDiscovery;

async function checkInvites(dryRun) {
  const execution = dryRun ? null : await require("./execution-permit").openPermit("discovery");
  const invitesUrl = ORIGIN + "/dashboard/invites";
  const readOnly = dryRun ? require("./voice123-readonly") : null;
  const browser = dryRun ? await readOnly.connectReadOnly() : await connect();
  const openPage = target => dryRun ? readOnly.readOnlyPage(browser, target) : browser.newPage();
  const report = { dryRun: true, discovered: 0, sheetsCheck: "Checked", projects: [] };
  try {
    const page = await openPage(invitesUrl);
    if (dryRun) {
      try {
        await page.goto(invitesUrl, CONFIG.navigation);
      } catch {
        throw new Error("Could not open the authenticated Voice123 dashboard in read-only mode");
      }
    } else {
      await handleLogin(page);
      await gotoInvitesWithRetry(page, invitesUrl, CONFIG.navigation);
    }
    const dashboard = new URL(page.url());
    if (dashboard.origin !== ORIGIN || dashboard.pathname.replace(/\/$/, "") !== "/dashboard/invites") {
      throw new Error("Voice123 invitations dashboard unavailable");
    }

    try {
      await page.waitForFunction((origin, source) => {
        const pattern = new RegExp(source, "i");
        return [...document.links].some(link => link.origin === origin && pattern.test(link.pathname) &&
          link.getClientRects().length && getComputedStyle(link).visibility === "visible" &&
          !link.closest('[hidden], [aria-hidden="true"]'));
      }, { timeout: 20000 }, ORIGIN, PROJECT_PATH.source);
    } catch (error) {
      if (error.name !== "TimeoutError" || await isCloudFrontBlocked(page)) throw error;
    }
    const discovered = await page.evaluate(projectLinks, ORIGIN, PROJECT_PATH.source);
    report.discovered = discovered.length;
    if (execution && !discovered.some(project => project.id === execution.permit.projectId)) {
      throw new Error("The permitted discovery project was not found");
    }
    if (!discovered.length) {
      report.sheetsCheck = "Skipped (no projects)";
      return dryRun ? report : [];
    }

    const history = await fs.readJson(historyPath).catch(error => {
      if (error.code === "ENOENT") return [];
      throw error;
    });
    if (!Array.isArray(history)) throw new Error("Invalid processed-projects history");
    let records;
    let sheets;
    try {
      sheets = require("./googleSheets");
      records = await sheets.getProjectRecords({ readOnly: dryRun });
    } catch (error) {
      if (!dryRun) throw error;
      report.sheetsCheck = "Unavailable";
      records = [];
    }
    const ids = entries => new Set(entries.map(record => projectIdentity(record?.url)?.id));
    const localIds = ids(history);
    const sheetIds = ids(records);
    const seen = new Set();
    const processed = [];
    let recordRecovery;
    let verifyPersistence;

    for (const candidate of dryRun ? discovered.slice(0, 3) : discovered.filter(project => project.id === execution.permit.projectId)) {
      if (seen.has(candidate.id)) continue;
      seen.add(candidate.id);
      const duplicateSources = [];
      if (localIds.has(candidate.id)) duplicateSources.push("Local history");
      if (sheetIds.has(candidate.id)) duplicateSources.push("Google Sheets");
      if (!dryRun && duplicateSources.length) throw new Error("The permitted discovery project already exists");

      const projectPage = await openPage(candidate.url);
      try {
        await projectPage.goto(candidate.url, CONFIG.navigation);
        await projectPage.waitForSelector(".project-management.specs .field-item, .project-specs .field-item, main .field-value-text", {
          timeout: 8000,
          visible: true
        }).catch(error => {
          if (error.name !== "TimeoutError") throw error;
        });
        await humanPause("after project open", 1400, 3200);
        if (projectIdentity(projectPage.url())?.id !== candidate.id || await isCloudFrontBlocked(projectPage)) {
          throw new Error("Voice123 specs unavailable");
        }

        const details = await projectPage.evaluate(readSpecs);
        const invitationStatus = candidate.conflictingStatus ? "Unknown" :
          candidate.invitationStatus === "Unknown" ? details.invitationStatus :
            details.invitationStatus !== "Unknown" && candidate.invitationStatus !== details.invitationStatus ? "Unknown" :
              candidate.invitationStatus;
        const readiness = auditionReadiness(details, invitationStatus);
        const rightsFlags = details.rightsFlags || [];

        const { description, clientId } = CONFIG.selectors.project;
        const project = {
          voice123Id: candidate.id, title: candidate.title, url: candidate.url, deadline: candidate.deadline,
          invitationStatus, proposalEligibility: details.proposalEligibility, auditionFieldStatus: details.fieldStatus,
          auditionFieldText: details.fieldText, attachments: details.attachments, rightsFlags,
          reviewReason: readiness.reason, status: "Needs Review",
          script: null,
          description: description ? await safeQuerySelector(projectPage, description, "No description") : "No description",
          clientId: clientId ? await safeQuerySelector(projectPage, clientId, "No client ID") : "No client ID"
        };
        const { fingerprint } = require("./approval-evidence");
        const approvalSha256 = fingerprint(project);
        if (dryRun) {
          const discoveryClarificationSha256 = await require("./execution-permit").discoveryClarification(candidate.id).catch(() => null);
          const actions = duplicateSources.length ? ["Skip existing processing record"] :
            report.sheetsCheck !== "Checked" ? ["No action planned until Sheets deduplication can be verified"] : [
              "Create Google Sheets row with status Needs Review",
              "Append processing history",
              ...(readiness.status === "Processing" ? ["Request human project review and generation approval"] : [])
            ];
          report.projects.push({
            id: candidate.id, title: candidate.title, url: candidate.url, deadline: candidate.deadline,
            invitationStatus, ...readiness,
            fieldStatus: details.fieldStatus, fieldCharacters: details.fieldText?.length || 0,
            attachments: details.attachments, rightsFlags, proposalEligibility: details.proposalEligibility,
            duplicateSources, actions, discoveryApprovalSha256: approvalSha256, discoveryClarificationSha256
          });
          continue;
        }

        if (history.some(item => item?.id === execution.permit.trackingId) ||
            records.some(item => item?.id === execution.permit.trackingId)) throw new Error("The permitted tracking ID already exists");
        const { discoveryClarification } = require("./execution-permit");
        const binding = {
          projectId: candidate.id, trackingId: execution.permit.trackingId, approvalSha256,
          clarificationSha256: await discoveryClarification(candidate.id)
        };
        const attemptId = randomUUID();
        await execution.claim(binding, attemptId);
        recordRecovery = require("./recovery-manifest").createRecoveryAttempt({
          operation: "discovery", permitId: execution.permit.id, attemptId, projectId: binding.projectId,
          trackingId: binding.trackingId, approvalSha256, clarificationSnapshotHash: binding.clarificationSha256
        });
        await recordRecovery("discovery-attempted");
        verifyPersistence = async () => execution.validate({
          ...binding, clarificationSha256: await discoveryClarification(candidate.id)
        }, attemptId);
        if (fingerprint(await projectPage.evaluate(readSpecs)) !== fingerprint(details) ||
            fingerprint((await page.evaluate(projectLinks, ORIGIN, PROJECT_PATH.source)).find(item => item.id === candidate.id) ?? null) !== fingerprint(candidate) ||
            (description && await safeQuerySelector(projectPage, description, "No description") !== project.description) ||
            (clientId && await safeQuerySelector(projectPage, clientId, "No client ID") !== project.clientId)) {
          throw new Error("Discovery evidence changed before persistence");
        }
        await verifyPersistence();
        const id = await sheets.addProject(project, binding.trackingId);
        if (id !== binding.trackingId) throw new Error("Discovery tracking ID did not match the permit");

        processed.push({ ...project, id });
      } catch (error) {
        if (!dryRun) throw error;
        console.warn(`Could not process Voice123 project ${candidate.id}: ${error.name}`);
        if (dryRun) report.projects.push({ id: candidate.id, title: candidate.title, duplicateSources, error: error.name, actions: [] });
      } finally {
        await projectPage.close();
      }
    }

    if (dryRun) return report;
    if (processed.length) {
      const temporaryPath = `${historyPath}.${process.pid}.tmp`;
      try {
        await verifyPersistence();
        await fs.writeJson(temporaryPath, [...history, ...processed], { spaces: 2, flag: "wx" });
        await verifyPersistence();
        await fs.rename(temporaryPath, historyPath);
      } catch (error) {
        throw new Error("Discovery persistence outcome requires manual reconciliation");
      }
    }
    if (recordRecovery) await recordRecovery("discovery-persisted");
    return processed;
  } finally {
    await browser.close();
  }
}

module.exports = {
  async checkInvites({ dryRun = process.env.DRY_RUN !== "false" } = {}) {
    if (dryRun !== true && process.env.DRY_RUN !== "false") throw new Error("Discovery persistence is disabled in dry-run mode");
    if (activeDiscovery) throw new Error("Voice123 discovery is already running");
    activeDiscovery = dryRun ? checkInvites(true) :
      require("./worker-lock").withWorkerLock(() => checkInvites(false));
    try {
      return await activeDiscovery;
    } finally {
      activeDiscovery = null;
    }
  },

  async uploadAudio(projectUrl, audioPath) {
    const { submitApprovedAudio } = require("./voice123-submission");
    return submitApprovedAudio(projectUrl, audioPath, { connect, handleLogin });
  }
};
