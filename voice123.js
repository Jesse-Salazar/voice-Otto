const HUMANIZE = {
  enabled: String(process.env.HUMANIZE_TRAFFIC || "true").toLowerCase() !== "false",
  minMs: Number(process.env.HUMANIZE_MIN_MS || 900),
  maxMs: Number(process.env.HUMANIZE_MAX_MS || 2600),
};

function randomInt(min, max) {
  const lo = Math.max(0, Number(min) || 0);
  const hi = Math.max(lo, Number(max) || lo);
  return Math.floor(Math.random() * (hi - lo + 1)) + lo;
}

async function humanPause(label = "", minMs = HUMANIZE.minMs, maxMs = HUMANIZE.maxMs) {
  if (!HUMANIZE.enabled) return;
  const ms = randomInt(minMs, maxMs);
  if (label) {
    console.log(`⏱️ Humanized pause (${label}): ${ms}ms`);
  }
  await waitFor(ms);
}

async function isCloudFrontBlocked(page) {
  try {
    return await page.evaluate(() => {
      const txt = (document.body?.innerText || "").toLowerCase();
      const title = (document.title || "").toLowerCase();
      return (
        title.includes("the request could not be satisfied") ||
        txt.includes("generated by cloudfront") ||
        txt.includes("request blocked")
      );
    });
  } catch (e) {
    return false;
  }
}

async function gotoInvitesWithRetry(page, url, navigationOptions, maxAttempts = 3) {
  let lastError = null;
  for (let attempt = 1; attempt <= maxAttempts; attempt++) {
    try {
      await humanPause("before invites navigation", 1200, 3000);
      await page.goto(url, navigationOptions);
      const blocked = await isCloudFrontBlocked(page);
      if (!blocked) return true;
      lastError = new Error("CloudFront block page detected");
      if (attempt < maxAttempts) {
        const delayMs = attempt * 5000;
        console.warn(`CloudFront block on invites page (attempt ${attempt}/${maxAttempts}), retrying in ${delayMs}ms...`);
        await waitFor(delayMs);
      }
    } catch (err) {
      lastError = err;
      if (attempt < maxAttempts) {
        const delayMs = attempt * 3000;
        console.warn(`Invites navigation failed (attempt ${attempt}/${maxAttempts}): ${err.message}. Retrying in ${delayMs}ms...`);
        await waitFor(delayMs);
      }
    }
  }
  throw lastError || new Error("Failed to load invites page");
}

