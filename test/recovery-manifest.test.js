const assert = require("node:assert/strict");
const { test } = require("node:test");
const fs = require("node:fs/promises");
const path = require("node:path");
const os = require("node:os");
const { createRecoveryAttempt, readRecoveryAttempts, classifyRecovery } = require("../recovery-manifest");

const storageUrl = "https://fixture.invalid/audio.mp3";
const audioSha256 = "c".repeat(64);
const context = operation => ({ operation, projectId: "SYNTHRECOVERY", trackingId: "fixture-track",
  approvalSha256: "a".repeat(64), clarificationSnapshotHash: "b".repeat(64) });

async function fixture(t) {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), "voice-otto-recovery-fixture-"));
  t.after(() => fs.rm(root, { recursive: true, force: true }));
  return path.join(await fs.realpath(root), "recovery");
}

test("generation recovery distinguishes a crash, generated bytes, ambiguous storage, and staged orphan candidates", async t => {
  const directory = await fixture(t);
  const record = createRecoveryAttempt(context("generation"), directory);
  const view = async rows => classifyRecovery((await readRecoveryAttempts(directory))[0], rows);
  await record("generation-started");
  assert.equal((await view()).finding, "provider-outcome-unknown");
  await record("audio-generated", { audioSha256 });
  assert.equal((await view()).finding, "generated-but-unstaged");
  await record("storage-attempted", { storageUrl });
  const unknown = await view();
  assert.equal(unknown.finding, "storage-outcome-unknown");
  assert.equal(unknown.storageUrl, storageUrl);
  await record("storage-confirmed");
  assert.equal((await view()).finding, "staged-orphan-candidate");
  const row = { projectId: context("generation").projectId, trackingId: context("generation").trackingId, storageUrl, audioSha256 };
  assert.equal((await view([{ ...row, projectId: "OTHER" }])).finding, "staged-orphan-candidate");
  assert.equal((await view([row])).finding, "staged-with-offline-row-match");
  await record("published");
  assert.equal((await view()).finding, "published");
  assert.equal((await view([])).finding, "published-reference-unverified");
  assert.equal((await view([])).cleanupAuthorized, false);
});

test("submission crash and completed confirmation before audit never authorize a retry", async t => {
  const directory = await fixture(t);
  const record = createRecoveryAttempt(context("submission"), directory);
  await record("submission-attempted", { storageUrl, audioSha256 });
  const before = classifyRecovery((await readRecoveryAttempts(directory))[0]);
  assert.equal(before.finding, "submission-outcome-unknown");
  assert.equal(before.automaticRetryAllowed, false);
  await record("submission-confirmed");
  const after = classifyRecovery((await readRecoveryAttempts(directory))[0]);
  assert.equal(after.finding, "confirmed-audit-pending");
  assert.equal(after.manualReconciliation, true);
  assert.equal(after.automaticRetryAllowed, false);
  await assert.rejects(record("submission-attempted", { storageUrl, audioSha256 }), /Invalid recovery record/);
});

test("recovery rejects invalid references, conflicting digests and torn records", async t => {
  const directory = await fixture(t);
  const record = createRecoveryAttempt(context("generation"), directory);
  await record("generation-started");
  await record("audio-generated", { audioSha256 });
  await assert.rejects(record("storage-attempted", { storageUrl: storageUrl + "?credential=fixture" }), /plain HTTPS/);
  await assert.rejects(record("storage-attempted", { storageUrl, audioSha256: "d".repeat(64) }), /Conflicting/);
  await record("storage-attempted", { storageUrl });
  const [name] = await fs.readdir(directory);
  const filename = path.join(directory, name);
  await fs.appendFile(filename, '{"partial":');
  await assert.rejects(readRecoveryAttempts(directory), /Incomplete recovery record/);
});
